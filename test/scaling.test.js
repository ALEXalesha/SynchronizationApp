'use strict';

// Закон масштаба: сеть на класс дефектов, а не замер на одно найденное место.
//
// Пять ревизий подряд находили тут одно и то же — произведение двух законных
// пределов, — и каждая закрывала находку точечным замером на тот адрес, который
// только что нашли: отметки на всё, закрытые узлы на файлы, исключения на индекс,
// разбор индекса на ветку, исключения на ветку в живом скане. Точечный замер
// знает ровно один адрес и молчит про соседний, поэтому следующая ревизия
// находила соседа — и объявляла закрытым уже его.
//
// Здесь спрашивается форма, а не адрес: растёт ОДНО измерение входа, остальные
// стоят на месте. Тогда линейная работа не меняется вовсе, и любое произведение
// с этим измерением вылезает само, в какой бы строке оно ни пряталось.
// Учетверение исключений на неизменном дереве — это ×1.2 у здорового кода
// и ×3.5 у любого, кто перебирает исключения внутри перебора веток. Разница
// втрое в обе стороны от порога, поэтому закон не дрожит от машины.
//
// Обе дороги меряются одним и тем же законом. Разошлись они уже дважды: правку
// делали на стороне с подсчётом размеров, а живой скан рядом оставался как был,
// и наоборот. Пока обе дороги под одним законом, зеркальная правка не может
// остаться незамеченной.
//
// Прогон идёт через настоящий обработчик предпросмотра — тот же код, что и в
// приложении, вместе со сборкой сканера в main.js.
//
// ЧЕГО ЭТОТ ЗАКОН НЕ СПРАШИВАЕТ. Произведение «ветки × размер индекса», если оно
// не трогает исключения: рост числа веток стоит линейно и сам по себе (каждая
// ветка — это свой readdir и свои stat), поэтому здоровый код на этой оси даёт
// ×3, а сломанный ×3.6, и разделить их порогом нельзя. Разделяются они только
// на индексе в десятки тысяч узлов, а столько файлов в прогоне создавать дороже,
// чем оно того стоит. Проверено: тот дефект (разбор индекса по разу на ветку)
// закон всё же ловит — но осью исключений, потому что разбор перебирал и их.

const { test } = require('node:test');
const assert = require('node:assert');
const fsp = require('node:fs').promises;
const os = require('node:os');
const path = require('node:path');

const { loadMain } = require('./helpers/main-harness');

const ВЕТОК = 400;
const ФАЙЛОВ_НА_ВЕТКУ = 2;
const ИСКЛЮЧЕНИЙ = 5000;
const K = 4;

// Считает обращения к диску и запоминает, сколько раз спрашивали каждый путь.
// Настоящие вызовы выполняются: закон меряет живое поведение, а не заглушку.
function подсчёт() {
  const statReal = fsp.stat;
  const readdirReal = fsp.readdir;
  const сколькоРаз = new Map();
  const обёртка = (real) => (p, ...rest) => {
    const key = String(p);
    сколькоРаз.set(key, (сколькоРаз.get(key) || 0) + 1);
    return real(p, ...rest);
  };
  fsp.stat = обёртка(statReal);
  fsp.readdir = обёртка(readdirReal);
  return {
    стоп() {
      fsp.stat = statReal;
      fsp.readdir = readdirReal;
      let худший = 0;
      for (const n of сколькоРаз.values()) if (n > худший) худший = n;
      return худший;
    },
  };
}

// Один предпросмотр. Дерево у всех прогонов одинаковое — меняется только число
// исключений, и в этом весь смысл: линейной работе расти неоткуда.
// сОбходом — вторая дорога: с готовым индексом план берёт файлы из памяти.
async function прогон(исключений, сОбходом) {
  const { call } = await loadMain();
  const src = await fsp.mkdtemp(path.join(os.tmpdir(), 'syncglass-масштаб-и-'));
  const dst = await fsp.mkdtemp(path.join(os.tmpdir(), 'syncglass-масштаб-п-'));
  try {
    const folders = [];
    for (let i = 0; i < ВЕТОК; i += 1) {
      // Общий предок у всех веток намеренный: его тип план спрашивал у диска
      // заново на каждую ветку, и это ловит закон о повторных вопросах.
      const rel = `год/квартал${i % 4}/ветка${i}`;
      folders.push(rel);
      await fsp.mkdir(path.join(src, rel), { recursive: true });
      for (let j = 0; j < ФАЙЛОВ_НА_ВЕТКУ; j += 1) {
        await fsp.writeFile(path.join(src, rel, `ф${j}.txt`), 'x');
      }
    }
    await fsp.mkdir(path.join(dst, 'год'), { recursive: true });

    // Исключения показывают на несуществующие пути: они обязаны стоить дёшево
    // сами по себе, работы от них не прибавляется.
    const excludes = [];
    for (let i = 0; i < исключений; i += 1) excludes.push(`${folders[i % ВЕТОК]}/нет${i}`);

    if (сОбходом) {
      await call('start-crawl', { localPath: src, networkPath: dst, noLimit: true });
    }

    const счёт = подсчёт();
    const начали = Date.now();
    // Направление указываем явно: без него стороны меняются местами, и закон
    // мерил бы разбор пустого дерева вместо настоящего.
    const res = await call('preview', {
      localPath: src, networkPath: dst, folders, excludes, direction: 'toNetwork',
    });
    const мс = Date.now() - начали;
    const худший = счёт.стоп();

    assert.ok(!res.error, `предпросмотр не отработал: ${res.error}`);
    assert.strictEqual(res.totals.copy, ВЕТОК * ФАЙЛОВ_НА_ВЕТКУ, 'план посчитан по всему дереву');
    return { мс, худший };
  } finally {
    await fsp.rm(src, { recursive: true, force: true });
    await fsp.rm(dst, { recursive: true, force: true });
  }
}

for (const сОбходом of [false, true]) {
  const дорога = сОбходом ? 'по индексу обхода' : 'живым сканом';

  test(`предпросмотр ${дорога}: вчетверо больше исключений — та же цена`, async () => {
    const мал = await прогон(ИСКЛЮЧЕНИЙ, сОбходом);
    const бол = await прогон(ИСКЛЮЧЕНИЙ * K, сОбходом);

    const рост = бол.мс / Math.max(мал.мс, 1);
    assert.ok(
      рост < 2,
      `исключений стало вчетверо больше, а цена выросла в ${рост.toFixed(1)} раз `
      + `(${мал.мс} → ${бол.мс} мс) при том же дереве: похоже на перебор исключений `
      + 'внутри перебора веток'
    );

    // Тот же прогон отвечает и на второй вопрос — он бесплатный, счётчик уже собран.
    // Повторное чтение одного узла на каждую ветку растёт линейно, поэтому осью
    // его не поймать, а на сетевой шаре именно оно стоит дороже всего: цепочка
    // родителей у пяти тысяч веток читалась пять тысяч раз, и всё это круги
    // до шары. Двойка в пороге, а не единица: корни сторон проверяются
    // на достижимость отдельно от разбора веток, и это законно.
    for (const { худший } of [мал, бол]) {
      assert.ok(
        худший <= 2,
        `один и тот же путь спрошен у диска ${худший} раз за предпросмотр: `
        + 'похоже на чтение заново внутри перебора'
      );
    }
  });
}
